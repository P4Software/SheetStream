using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace SheetStream.Generators
{
    /// <summary>Writes the C# for one <see cref="SheetRowModel"/>. Pure string building; no symbols are touched here.</summary>
    internal static class SheetRowEmitter
    {
        private const string MapperClassName = "SheetStreamGeneratedMapper";

        public static string Emit(SheetRowModel model, bool moduleInitializer)
        {
            var w = new Writer();
            w.Line("// <auto-generated>");
            w.Line("//     Generated by SheetStream.Generators from the members of " + model.FullyQualifiedName + ".");
            w.Line("//     Changes to this file are lost when the project is rebuilt; change the [SheetColumn] attributes instead.");
            w.Line("// </auto-generated>");
            w.Line("#nullable enable");
            // Consumers often build with TreatWarningsAsErrors and custom analyzer sets; generated code must never break their build.
            w.Line("#pragma warning disable");
            w.Line();

            if (model.Namespace != null)
            {
                w.Line("namespace " + model.Namespace);
                w.Open();
            }
            foreach (var declaration in model.ContainingDeclarations)
            {
                w.Line(declaration);
                w.Open();
            }

            w.Line(model.Declaration);
            w.Open();
            EmitTypeMembers(w, model, moduleInitializer);
            w.Close();

            for (var i = 0; i < model.ContainingDeclarations.Count; i++) w.Close();
            if (model.Namespace != null) w.Close();
            return w.ToString();
        }

        private static void EmitTypeMembers(Writer w, SheetRowModel model, bool moduleInitializer)
        {
            var t = model.FullyQualifiedName;
            var mapperType = "global::SheetStream.ISheetRowMapper<" + t + ">";

            w.Line("/// <summary>Column mapping generated at compile time by SheetStream from the public members of this type.</summary>");
            w.Line("public static " + mapperType + " SheetMapper { get; } = new " + MapperClassName + "();");
            w.Line();

            w.Line("/// <summary>");
            w.Line("/// Registers <see cref=\"SheetMapper\"/> with <see cref=\"global::SheetStream.SheetMappers\"/> so LoadFromCollection and");
            w.Line("/// ExcelReader.Read use it instead of reflection." + (moduleInitializer
                ? " Runs automatically when the module loads."
                : " Call it once at start-up (this target framework has no module initializers)."));
            w.Line("/// </summary>");
            if (moduleInitializer) w.Line("[global::System.Runtime.CompilerServices.ModuleInitializer]");
            w.Line("public static void RegisterSheetMapper() => global::SheetStream.SheetMappers.Register<" + t + ">(SheetMapper);");
            w.Line();

            w.Line("private sealed class " + MapperClassName + " : " + mapperType);
            w.Open();

            // Headers and formats as static arrays: built once, shared by every call.
            w.Line("private static readonly string[] HeaderNames = new string[]");
            w.Open();
            foreach (var c in model.Columns) w.Line(Literal(c.Header) + ",");
            w.CloseWith(";");
            w.Line();
            w.Line("private static readonly string?[] FormatCodes = new string?[]");
            w.Open();
            foreach (var c in model.Columns) w.Line((c.NumberFormat == null ? "null" : Literal(c.NumberFormat)) + ",");
            w.CloseWith(";");
            w.Line();

            w.Line("public global::System.Collections.Generic.IReadOnlyList<string> Headers => HeaderNames;");
            w.Line("public global::System.Collections.Generic.IReadOnlyList<string?> NumberFormats => FormatCodes;");
            w.Line("public bool CanRead => " + (model.CanCreate ? "true" : "false") + ";");
            w.Line();

            // MemberType
            w.Line("public global::System.Type MemberType(int column)");
            w.Open();
            w.Line("switch (column)");
            w.Open();
            for (var i = 0; i < model.Columns.Count; i++) w.Line("case " + i + ": return typeof(" + model.Columns[i].TypeForTypeOf + ");");
            w.Line("default: throw new global::System.ArgumentOutOfRangeException(nameof(column));");
            w.Close();
            w.Close();
            w.Line();

            // CanSet
            w.Line("public bool CanSet(int column)");
            w.Open();
            w.Line("switch (column)");
            w.Open();
            for (var i = 0; i < model.Columns.Count; i++)
                if (model.Columns[i].CanSet) w.Line("case " + i + ":");
            if (model.Columns.Any(c => c.CanSet)) w.Line("    return true;");
            w.Line("default: return false;");
            w.Close();
            w.Close();
            w.Line();

            // FindColumn: same precedence as the reflection reader's name dictionary. Explicit [SheetColumn]
            // names overwrite anything (so the last one declared wins); [DisplayName] and member names are only
            // added when the key is still free (so the first one declared wins). Only settable columns take part.
            w.Line("public int FindColumn(string header)");
            w.Open();
            w.Line("if (header == null) return -1;");
            for (var i = model.Columns.Count - 1; i >= 0; i--)
            {
                var c = model.Columns[i];
                if (c.CanSet && c.ExplicitName != null) w.Line("if (" + Matches(c.ExplicitName) + ") return " + i + ";");
            }
            for (var i = 0; i < model.Columns.Count; i++)
            {
                var c = model.Columns[i];
                if (!c.CanSet) continue;
                if (c.DisplayName != null) w.Line("if (" + Matches(c.DisplayName) + ") return " + i + ";");
                w.Line("if (" + Matches(c.MemberName) + ") return " + i + ";");
            }
            w.Line("return -1;");
            w.Close();
            w.Line();

            // WriteRow: typed WriteCell per member, so no value is boxed on the hot path.
            w.Line("public void WriteRow(" + t + " item, global::SheetStream.RowWriter row, global::SheetStream.Styles.CellStyle?[] styles)");
            w.Open();
            for (var i = 0; i < model.Columns.Count; i++) w.Line(WriteCell(model.Columns[i], "item." + model.Columns[i].MemberName, "styles[" + i + "]"));
            w.Close();
            w.Line();

            // GetValue
            w.Line("public object? GetValue(" + t + " item, int column)");
            w.Open();
            w.Line("switch (column)");
            w.Open();
            for (var i = 0; i < model.Columns.Count; i++) w.Line("case " + i + ": return item." + model.Columns[i].MemberName + ";");
            w.Line("default: throw new global::System.ArgumentOutOfRangeException(nameof(column));");
            w.Close();
            w.Close();
            w.Line();

            // Create
            w.Line("public " + t + " Create()");
            w.Open();
            if (model.CanCreate) w.Line("return new " + t + "();");
            else w.Line("throw new global::System.NotSupportedException(\"" + model.TypeName + " has no parameterless constructor, so its SheetMapper can only write rows.\");");
            w.Close();
            w.Line();

            // SetValue: value is already converted to MemberType (or null). Non-nullable value types treat null
            // as default, which is what reflection's PropertyInfo.SetValue(obj, null) does.
            w.Line("public void SetValue(ref " + t + " item, int column, object? value)");
            w.Open();
            w.Line("switch (column)");
            w.Open();
            for (var i = 0; i < model.Columns.Count; i++)
            {
                var c = model.Columns[i];
                if (!c.CanSet) { w.Line("case " + i + ": return; // read-only member"); continue; }
                string cast;
                if (c.IsValueType && !c.IsNullableValueType) cast = "value is null ? default : (" + c.TypeForCast + ")value";
                else if (c.IsNonNullableReference) cast = "(" + c.TypeForCast + ")value!";
                else cast = "(" + c.TypeForCast + ")value";
                w.Line("case " + i + ": item." + c.MemberName + " = " + cast + "; return;");
            }
            w.Line("default: throw new global::System.ArgumentOutOfRangeException(nameof(column));");
            w.Close();
            w.Close();

            w.Close(); // mapper class
        }

        private static string Matches(string name)
            => "string.Equals(header, " + Literal(name) + ", global::System.StringComparison.OrdinalIgnoreCase)";

        /// <summary>One statement writing a member through the typed overload that <c>WriteCell(object?)</c> would pick.</summary>
        private static string WriteCell(ColumnModel c, string access, string style)
        {
            if (c.IsNullableValueType)
            {
                // Nullable<T>: unwrap once; an empty value becomes an empty cell exactly like a null object does.
                return "if (" + access + ".HasValue) row.WriteCell(" + Converted(c.Kind, access + ".GetValueOrDefault()") + ", " + style + "); else row.WriteEmpty(" + style + ");";
            }
            return "row.WriteCell(" + Converted(c.Kind, access) + ", " + style + ");";
        }

        private static string Converted(WriteKind kind, string expression)
        {
            switch (kind)
            {
                case WriteKind.CastInt: return "(int)" + expression;
                case WriteKind.CastLong: return "(long)" + expression;
                case WriteKind.CastDouble: return "(double)" + expression;
                case WriteKind.ToString: return expression + ".ToString()";
                case WriteKind.Object: return "(object?)" + expression;
                default: return expression;
            }
        }

        private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

        /// <summary>Minimal indenting writer; keeps the emitted file readable when users open it from "Analyzers" in the IDE.</summary>
        private sealed class Writer
        {
            private readonly StringBuilder _sb = new StringBuilder();
            private int _indent;

            public void Line(string text = "")
            {
                if (text.Length == 0) { _sb.AppendLine(); return; }
                _sb.Append(' ', _indent * 4).AppendLine(text);
            }

            public void Open()
            {
                Line("{");
                _indent++;
            }

            public void Close() => CloseWith("");

            public void CloseWith(string suffix)
            {
                _indent--;
                Line("}" + suffix);
            }

            public override string ToString() => _sb.ToString();
        }
    }
}
